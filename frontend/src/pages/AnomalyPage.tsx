import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  ShieldAlert,
  AlertTriangle,
  RefreshCw,
  Eye,
  CheckCircle2,
  AlertCircle,
  FileText,
  Building2,
  ExternalLink,
  HelpCircle,
  X
} from 'lucide-react';
import { api } from '../services/api';
import { AnomalyReport } from '../types';
import { useAuth } from '../context/AuthContext';
import { useToast } from '../context/ToastContext';

export const AnomalyPage: React.FC = () => {
  const navigate = useNavigate();
  const { user } = useAuth();
  const { showToast } = useToast();

  const [anomalies, setAnomalies] = useState<AnomalyReport[]>([]);
  const [loading, setLoading] = useState(true);
  const [minScore, setMinScore] = useState<number>(10);
  const [selectedAnomaly, setSelectedAnomaly] = useState<AnomalyReport | null>(null);
  const [reviewDecision, setReviewDecision] = useState('Manual Review Completed - Authenticity Cleared');
  const [reviewNotes, setReviewNotes] = useState('');
  const [isSavingDecision, setIsSavingDecision] = useState(false);

  const loadData = async () => {
    try {
      setLoading(true);
      const data = await api.getAnomalies({ min_score: minScore.toString() });
      setAnomalies(data);
    } catch (err: any) {
      showToast(err.message || 'Failed to load anomaly reports', 'error');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadData();
  }, [minScore]);

  const handleRecordDecision = async () => {
    if (!selectedAnomaly) return;
    try {
      setIsSavingDecision(true);
      await api.recordAnomalyDecision(selectedAnomaly.document_id, reviewDecision, reviewNotes);
      showToast('Anomaly review decision recorded on audit trail.', 'success');
      setSelectedAnomaly(null);
      setReviewNotes('');
      loadData();
    } catch (err: any) {
      showToast(err.message || 'Failed to save review', 'error');
    } finally {
      setIsSavingDecision(false);
    }
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-extrabold text-slate-900 tracking-tight">
            Multi-Signal Document Anomaly Detection
          </h1>
          <p className="text-sm text-slate-500 mt-0.5">
            Cryptographic SHA-256 duplicate verification, date consistency inspection, and legibility scrutiny.
          </p>
        </div>
        <button
          onClick={loadData}
          className="inline-flex items-center gap-1.5 px-3 py-2 text-xs font-semibold text-slate-700 bg-white border border-slate-200 rounded-xl hover:bg-slate-50 shadow-2xs transition-colors cursor-pointer"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          Re-scan Documents
        </button>
      </div>

      {/* Regulatory Guardrail Disclaimer */}
      <div className="p-4 bg-slate-900 text-white rounded-2xl border border-slate-800 text-xs flex items-start gap-3">
        <ShieldAlert className="w-5 h-5 text-amber-400 shrink-0 mt-0.5" />
        <div>
          <div className="font-bold text-amber-300">Regulatory Decision-Support Notice</div>
          <p className="text-slate-300 mt-1 leading-relaxed">
            Flags generated by this module are labelled <strong>"Potential Anomaly / Review Required"</strong>. Automated anomaly scores never declare a statutory document altered or forged on AI heuristics alone. All findings require human examiner scrutiny and authorized verification against issuing authority registers.
          </p>
        </div>
      </div>

      {/* Filter Bar */}
      <div className="bg-white p-4 rounded-2xl border border-slate-200 shadow-2xs flex flex-wrap items-center justify-between gap-3 text-xs">
        <div className="flex items-center gap-3">
          <span className="font-semibold text-slate-700">Filter by Minimum Anomaly Score:</span>
          <div className="flex items-center gap-2">
            {[10, 25, 45].map((score) => (
              <button
                key={score}
                onClick={() => setMinScore(score)}
                className={`px-3 py-1 rounded-lg font-bold transition-all cursor-pointer ${
                  minScore === score
                    ? 'bg-blue-600 text-white shadow-xs'
                    : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
                }`}
              >
                {score}+ Points
              </button>
            ))}
          </div>
        </div>

        <div className="text-slate-500">
          Identified <strong className="text-slate-800">{anomalies.length}</strong> flagged documents across dossiers
        </div>
      </div>

      {/* Anomaly Cards Grid */}
      <div className="space-y-4">
        {anomalies.length === 0 ? (
          <div className="bg-white p-12 text-center rounded-2xl border border-slate-200 text-slate-500">
            <CheckCircle2 className="w-10 h-10 text-emerald-500 mx-auto mb-2" />
            <h3 className="font-bold text-slate-800">No Anomaly Flags Detected</h3>
            <p className="text-xs text-slate-400 mt-1">All uploaded files meet baseline cryptographic and chronological consistency criteria.</p>
          </div>
        ) : (
          anomalies.map((item) => {
            const isHigh = item.risk_level === 'High';
            const isMed = item.risk_level === 'Medium';

            return (
              <div
                key={item.document_id}
                className="bg-white p-5 rounded-2xl border border-slate-200 shadow-2xs hover:shadow-md transition-all space-y-4"
              >
                {/* Header */}
                <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-3 pb-3 border-b border-slate-100">
                  <div>
                    <div className="flex items-center gap-2 mb-1">
                      <span
                        className={`px-2.5 py-0.5 rounded-full text-[11px] font-extrabold uppercase border ${
                          isHigh
                            ? 'bg-rose-50 text-rose-700 border-rose-300'
                            : isMed
                            ? 'bg-amber-50 text-amber-700 border-amber-300'
                            : 'bg-blue-50 text-blue-700 border-blue-300'
                        }`}
                      >
                        {item.risk_level} Risk • Score {item.anomaly_score}/100
                      </span>
                      <span className="font-mono text-xs font-bold text-blue-600">
                        {item.application_number}
                      </span>
                    </div>

                    <h3 className="font-bold text-base text-slate-900">{item.institution_name}</h3>
                    <div className="text-xs text-slate-500 mt-0.5">
                      Target File: <strong className="text-slate-800">{item.filename}</strong> ({item.document_type})
                    </div>
                  </div>

                  <div className="flex items-center gap-2">
                    <a
                      href={item.download_url}
                      target="_blank"
                      rel="noreferrer"
                      className="px-3 py-1.5 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl text-xs font-semibold inline-flex items-center gap-1.5 transition-colors"
                    >
                      <Eye className="w-3.5 h-3.5" /> View Scan
                    </a>

                    {(user?.role === 'reviewer' || user?.role === 'admin') && (
                      <button
                        onClick={() => setSelectedAnomaly(item)}
                        className="px-3 py-1.5 bg-blue-600 hover:bg-blue-700 text-white rounded-xl text-xs font-bold shadow-2xs transition-all cursor-pointer"
                      >
                        Record Officer Observation
                      </button>
                    )}
                  </div>
                </div>

                {/* Signals Breakdown */}
                <div className="space-y-2">
                  <div className="text-[11px] font-bold text-slate-400 uppercase tracking-wider">
                    Contributing Anomaly Signals ({item.signals.length})
                  </div>
                  <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
                    {item.signals.map((sig, idx) => (
                      <div
                        key={idx}
                        className="p-3 rounded-xl bg-slate-50 border border-slate-200/80 text-xs space-y-1"
                      >
                        <div className="flex items-center justify-between font-bold text-slate-900">
                          <span>{sig.title}</span>
                          <span className="text-[10px] text-rose-600 font-mono">+{sig.points} pts</span>
                        </div>
                        <p className="text-slate-600 text-[11px]">{sig.explanation}</p>
                        <div className="text-[11px] text-blue-900 bg-blue-50/80 p-1.5 rounded-lg font-mono">
                          {sig.evidence}
                        </div>
                      </div>
                    ))}
                  </div>
                </div>

                {/* Recommended Action Footer */}
                <div className="pt-2 text-xs flex flex-col sm:flex-row sm:items-center justify-between gap-2 text-slate-600">
                  <div>
                    <strong>Action:</strong> {item.recommended_action}
                  </div>
                  <button
                    onClick={() => navigate(`/applications/${item.application_id}`)}
                    className="text-blue-600 font-semibold hover:underline text-xs flex items-center gap-1"
                  >
                    Go to Application Dossier →
                  </button>
                </div>
              </div>
            );
          })
        )}
      </div>

      {/* Review Observation Modal */}
      {selectedAnomaly && (
        <div className="fixed inset-0 z-50 bg-slate-900/60 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white rounded-2xl max-w-md w-full p-6 shadow-2xl border border-slate-200 animate-in fade-in zoom-in-95 duration-150">
            <div className="flex items-center justify-between pb-3 border-b border-slate-100">
              <h3 className="font-bold text-base text-slate-900">Record Anomaly Scrutiny Decision</h3>
              <button onClick={() => setSelectedAnomaly(null)} className="text-slate-400 hover:text-slate-600">
                <X className="w-5 h-5" />
              </button>
            </div>

            <div className="py-4 space-y-3.5 text-xs">
              <div className="p-3 bg-slate-50 rounded-xl border border-slate-200">
                <div className="font-bold text-slate-900">{selectedAnomaly.filename}</div>
                <div className="text-slate-500 mt-0.5">Anomaly Score: {selectedAnomaly.anomaly_score}/100</div>
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">Examiner Finding Disposition</label>
                <select
                  value={reviewDecision}
                  onChange={(e) => setReviewDecision(e.target.value)}
                  className="w-full px-3 py-2 border border-slate-300 rounded-xl text-xs font-semibold focus:outline-none"
                >
                  <option value="Manual Review Completed - Authenticity Cleared">Manual Review Completed - Authenticity Cleared</option>
                  <option value="Clarification Requested - Suspected File Duplication">Clarification Requested - Suspected File Duplication</option>
                  <option value="Physical Verification Mandated">Physical Verification Mandated</option>
                  <option value="Escalated to Vigilance Committee">Escalated to Vigilance Committee</option>
                </select>
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">Examiner Detailed Notes</label>
                <textarea
                  rows={3}
                  required
                  placeholder="Record formal reasons after examining original high-res scans or external gazettes..."
                  value={reviewNotes}
                  onChange={(e) => setReviewNotes(e.target.value)}
                  className="w-full px-3 py-2 border border-slate-300 rounded-xl text-xs"
                />
              </div>
            </div>

            <div className="pt-3 border-t border-slate-100 flex justify-end gap-2 text-xs">
              <button onClick={() => setSelectedAnomaly(null)} className="px-3 py-1.5 text-slate-600 hover:bg-slate-100 rounded-xl font-medium">
                Cancel
              </button>
              <button
                onClick={handleRecordDecision}
                disabled={isSavingDecision}
                className="px-4 py-2 bg-blue-600 hover:bg-blue-700 text-white font-bold rounded-xl cursor-pointer"
              >
                {isSavingDecision ? 'Saving...' : 'Record Decision to Audit Log'}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
